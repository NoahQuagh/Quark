package com.noahquagh.quark.model;

/**
 * Catégories fondamentales des patrons de conception selon la classification du Gang of Four (GoF).
 *
 * @author noahq
 * @version 1.2
 */
public enum PatternCategory {
    /** Patrons dédiés aux mécanismes d'instanciation et de création d'objets. */
    CREATIONAL,
    /** Patrons dédiés à la composition et à l'assemblage des classes et des objets. */
    STRUCTURAL,
    /** Patrons dédiés à la communication et à la répartition des responsabilités entre objets. */
    BEHAVIORAL
}
